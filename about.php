            <h1>About ImmuniTrack</h1>
            <p>
                ImmuniTrack was created to solve the challenges small clinics face in managing vaccination records. 
                During the COVID-19 pandemic, many clinics relied on paper-based records, which often led to lost, damaged, or unclear documentation. 
                Patients struggled to get proof of vaccination quickly, and clinic staff spent a lot of time manually searching through files. 
                This inspired the development of a web-based system that organizes vaccination data digitally, allowing staff to record information efficiently and patients to access their vaccination history online. 
                The system focuses on common vaccines such as COVID-19, influenza, dengue, chickenpox, and anti-rabies, and is designed to be simple, secure, and practical for small community clinics.
            </p>
